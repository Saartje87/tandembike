/** The category a triage proposal recommends. */
export const triageCategories = ['bug', 'enhancement'] as const;

export type TriageCategory = (typeof triageCategories)[number];

/** The state a triage proposal recommends. */
export const triageStates = [
  'ready-for-agent',
  'ready-for-human',
  'needs-info',
  'wontfix',
] as const;

export type TriageState = (typeof triageStates)[number];

/** Where a proposal stands: only a pending one can be approved or rejected. */
export const triageProposalStatuses = [
  'pending',
  'approved',
  'rejected',
  'superseded',
] as const;

export type TriageProposalStatus = (typeof triageProposalStatuses)[number];

/** One Ticket a split proposal would file. */
export type TriageSplit = {
  title: string;
  description: string;
  acceptanceCriteria: string[];
};

/** The line every triage comment starts with. */
export const triageDisclaimer = '> *This was generated by AI during triage.*';
