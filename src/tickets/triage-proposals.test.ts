// @vitest-environment node
import { describe, expect, it } from 'vitest';

import { createTestTickets, errorFrom } from '../test/tickets';
import { NotAllowedError, ValidationError } from './errors';

const setUp = (actor: 'user' | 'agent' = 'user') => {
  const tickets = createTestTickets(undefined, actor);
  const project = tickets.createProject({ name: 'Website' });
  const ticket = tickets.createTicket({
    projectId: project.id,
    title: 'Fix the header',
    labels: ['needs-triage'],
    acceptanceCriteria: [{ text: 'Old criterion' }],
  });
  return { tickets, project, ticket };
};

const proposal = {
  category: 'bug' as const,
  state: 'ready-for-agent' as const,
  reasoning: 'The header overlaps at narrow widths.',
};

describe('proposeTriage', () => {
  it('records a pending proposal and posts the reasoning with the AI disclaimer', () => {
    const { tickets, ticket } = setUp();

    const made = tickets.proposeTriage(ticket.number, {
      ...proposal,
      acceptanceCriteria: ['Header fits at 320px'],
      runId: '12',
    });

    expect(made).toMatchObject({
      ticketNumber: ticket.number,
      category: 'bug',
      state: 'ready-for-agent',
      acceptanceCriteria: ['Header fits at 320px'],
      runId: '12',
      status: 'pending',
      duplicateOf: null,
      splits: null,
      decidedAt: null,
    });
    expect(tickets.pendingTriage(ticket.number)).toEqual(made);
    expect(tickets.listComments(ticket.number).map((c) => c.body)).toEqual([
      '> *This was generated by AI during triage.*\n\nThe header overlaps at narrow widths.',
    ]);
    expect(tickets.listComments(ticket.number)[0].author).toBe('agent');
  });

  it('leaves the labels and criteria alone', () => {
    const { tickets, ticket } = setUp();

    tickets.proposeTriage(ticket.number, proposal);

    const after = tickets.getTicket(ticket.number);
    expect(after.labels).toEqual(['needs-triage']);
    expect(after.acceptanceCriteria.map((c) => c.text)).toEqual([
      'Old criterion',
    ]);
  });

  it('supersedes a pending proposal with a newer one', () => {
    const { tickets, ticket } = setUp();
    const first = tickets.proposeTriage(ticket.number, proposal);

    const second = tickets.proposeTriage(ticket.number, {
      ...proposal,
      state: 'needs-info',
    });

    expect(tickets.pendingTriage(ticket.number)?.id).toBe(second.id);
    expect(tickets.getTriageProposal(first.id).status).toBe('superseded');
  });

  it('records Activity', () => {
    const { tickets, ticket } = setUp('agent');

    tickets.proposeTriage(ticket.number, proposal);

    const last = tickets.listActivity(ticket.number).at(-1);
    expect(last?.actor).toBe('agent');
    expect(last?.changes).toEqual([
      { type: 'triageProposed', category: 'bug', state: 'ready-for-agent' },
    ]);
  });

  it('refuses a Ticket that is not Todo', () => {
    const { tickets, ticket } = setUp();
    tickets.updateTicket(ticket.number, { status: 'In progress' });

    expect(
      errorFrom(() => tickets.proposeTriage(ticket.number, proposal)),
    ).toBeInstanceOf(NotAllowedError);
    expect(tickets.pendingTriage(ticket.number)).toBeNull();
  });

  it('refuses a duplicate or splits for now', () => {
    const { tickets, ticket } = setUp();

    expect(
      errorFrom(() =>
        tickets.proposeTriage(ticket.number, { ...proposal, duplicateOf: 99 }),
      ),
    ).toBeInstanceOf(ValidationError);
    expect(
      errorFrom(() =>
        tickets.proposeTriage(ticket.number, {
          ...proposal,
          splits: [{ title: 'A', description: '', acceptanceCriteria: [] }],
        }),
      ),
    ).toBeInstanceOf(ValidationError);
  });

  it('refuses an unknown category or state, and empty reasoning', () => {
    const { tickets, ticket } = setUp();

    const error = errorFrom(() =>
      tickets.proposeTriage(ticket.number, {
        category: 'chore' as never,
        state: 'done' as never,
        reasoning: '  ',
      }),
    ) as ValidationError;

    expect(Object.keys(error.fieldErrors).sort()).toEqual([
      'category',
      'reasoning',
      'state',
    ]);
  });
});

describe('approveTriage', () => {
  it('sets the category and state, swapping the old state label, and replaces the criteria', () => {
    const { tickets, ticket } = setUp();
    tickets.addLabels(ticket.number, ['enhancement']);
    const made = tickets.proposeTriage(ticket.number, {
      ...proposal,
      acceptanceCriteria: ['New one', 'New two'],
    });

    tickets.approveTriage(made.id, {});

    const after = tickets.getTicket(ticket.number);
    expect(after.labels).toEqual(['bug', 'ready-for-agent']);
    expect(after.acceptanceCriteria.map((c) => c.text)).toEqual([
      'New one',
      'New two',
    ]);
    expect(tickets.getTriageProposal(made.id)).toMatchObject({
      status: 'approved',
    });
    expect(tickets.pendingTriage(ticket.number)).toBeNull();
  });

  it('keeps the criteria when none were proposed', () => {
    const { tickets, ticket } = setUp();
    const made = tickets.proposeTriage(ticket.number, proposal);

    tickets.approveTriage(made.id, {});

    expect(
      tickets.getTicket(ticket.number).acceptanceCriteria.map((c) => c.text),
    ).toEqual(['Old criterion']);
  });

  it('applies the overridden category and state', () => {
    const { tickets, ticket } = setUp();
    const made = tickets.proposeTriage(ticket.number, proposal);

    tickets.approveTriage(made.id, {
      category: 'enhancement',
      state: 'ready-for-human',
    });

    expect(tickets.getTicket(ticket.number).labels).toEqual([
      'enhancement',
      'ready-for-human',
    ]);
  });

  it('wontfix replaces the state label with wontfix', () => {
    const { tickets, ticket } = setUp();
    const made = tickets.proposeTriage(ticket.number, {
      ...proposal,
      state: 'wontfix',
    });

    tickets.approveTriage(made.id, {});

    expect(tickets.getTicket(ticket.number).labels).toEqual(['bug', 'wontfix']);
  });

  it('records Activity of the decision', () => {
    const { tickets, ticket } = setUp();
    const made = tickets.proposeTriage(ticket.number, proposal);

    tickets.approveTriage(made.id, { state: 'needs-info' });

    expect(tickets.listActivity(ticket.number).at(-1)?.changes).toEqual([
      { type: 'triageApproved', category: 'bug', state: 'needs-info' },
    ]);
  });

  it('refuses a decided proposal, and one on a Ticket that left Todo, changing nothing', () => {
    const { tickets, ticket } = setUp();
    const made = tickets.proposeTriage(ticket.number, proposal);
    tickets.rejectTriage(made.id);
    expect(errorFrom(() => tickets.approveTriage(made.id, {}))).toBeInstanceOf(
      NotAllowedError,
    );

    const next = tickets.proposeTriage(ticket.number, proposal);
    tickets.updateTicket(ticket.number, { status: 'In progress' });
    expect(errorFrom(() => tickets.approveTriage(next.id, {}))).toBeInstanceOf(
      NotAllowedError,
    );
    expect(tickets.getTicket(ticket.number).labels).toEqual(['needs-triage']);
  });

  it('refuses an unknown override', () => {
    const { tickets, ticket } = setUp();
    const made = tickets.proposeTriage(ticket.number, proposal);

    expect(
      errorFrom(() =>
        tickets.approveTriage(made.id, { state: 'done' as never }),
      ),
    ).toBeInstanceOf(ValidationError);
    expect(tickets.pendingTriage(ticket.number)?.id).toBe(made.id);
  });
});

describe('rejectTriage', () => {
  it('rejects, adding the reason as a comment by the User', () => {
    const { tickets, ticket } = setUp();
    const made = tickets.proposeTriage(ticket.number, proposal);

    tickets.rejectTriage(made.id, 'Not a bug');

    expect(tickets.getTriageProposal(made.id).status).toBe('rejected');
    expect(tickets.getTicket(ticket.number).labels).toEqual(['needs-triage']);
    const comments = tickets.listComments(ticket.number);
    expect(comments.at(-1)).toMatchObject({
      body: 'Not a bug',
      author: 'user',
    });
    expect(tickets.listActivity(ticket.number).at(-1)?.changes).toEqual([
      { type: 'triageRejected' },
    ]);
  });

  it('adds no comment without a reason', () => {
    const { tickets, ticket } = setUp();
    const made = tickets.proposeTriage(ticket.number, proposal);

    tickets.rejectTriage(made.id, '  ');

    expect(tickets.listComments(ticket.number)).toHaveLength(1);
  });
});

describe('triage reads', () => {
  it('lists the Tickets of a Project with a pending proposal', () => {
    const { tickets, project, ticket } = setUp();
    const other = tickets.createTicket({ projectId: project.id, title: 'B' });
    tickets.proposeTriage(ticket.number, proposal);
    const done = tickets.proposeTriage(other.number, proposal);
    tickets.rejectTriage(done.id);

    expect(tickets.pendingTriageNumbers(project.id)).toEqual([ticket.number]);
  });
});
